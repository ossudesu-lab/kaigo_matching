// 旧・本番プロンプト（git HEAD 時点の api/extract.js が持っていたもの）。
//
// 比較用のベースラインとして保存している。改善の before / after を後から
// 誰でも再現できるようにするのが目的。**本番はこれを使っていない。**
//
// 現行（api/_lib/extract-prompt.js）との差:
//   ・年を補う指示が無い（記録文は「6/4」形式なので date が外れる想定）
//   ・staff の正規化ルールが無い（姓のみ・敬称なし／自施設職員と利用者名の除外）
//   ・discrepancy の「軽微な変化 / 実質的な負荷差」の線引きが無い
//   ・medical の「曖昧な表現では true にしない」が無い
//   ・「盛らない」方針ブロックが無い
//
// 使い方:
//   node --env-file=.env scripts/eval-extract.js --prompt=scripts/prompt-variants/baseline-v1.js

// 現行の buildPrompt と同じ呼び出し方ができるよう第2引数を受け取るが、使わない。
// 「年を補う指示が無かった」ことをコード上でも明示するため、意図的に無視している。
export function buildPrompt(text, _opts) {
  return `あなたは介護施設の利用記録を読み取るアシスタントです。次の記録文から項目を抽出し、JSONだけを返してください。

【記録文】
${text}

抽出項目（不明なものは空文字 "" または false）:
- date: 利用日。YYYY-MM-DD形式。無ければ ""
- kyotaku: 紹介元の居宅・ケアマネ事業所名。無ければ ""
- staff: 紹介元の担当ケアマネの氏名（姓のみで可）。書かれていなければ ""
- care: 要介護度。次のどれかに厳密一致（要支援1／要支援2／要介護1／要介護2／要介護3／要介護4／要介護5）。不明なら ""
- medical: インスリン・点滴・痰吸引・褥瘡処置など看護師対応が要る処置があれば true
- result: "regular"（定期確定）／"single"（単発終了）／"watch"（未確定・様子見）。判断できなければ "watch"
- trouble: 現場で問題やトラブルがあれば true
- discrepancy: 事前の申し送り・情報と実際の様子が食い違っていたら true
- summary: 様子を1〜2文で簡潔にまとめた文

必ずJSONオブジェクトのみを返す。前置き・説明・マークダウン記号は一切つけない。`;
}
