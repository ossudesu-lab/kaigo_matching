// ローカルLLM（7B級）向けに書き直した抽出プロンプト。
//
// ── なぜ別に用意するか ──
// 本番プロンプト（api/_lib/extract-prompt.js）は Claude 向けに育ててきたもので、
// 入力1,269トークン、入れ子の条件と否定文が多い。7B級のモデルには複雑すぎる。
// qwen2.5:7b で測ると総合94点・重大な見逃し11.7件/回だった（2026-08、35ケース×3回）。
//
// 「同じプロンプトで比較」は公平だが、実運用ではモデルに合わせて調整する。
// そこまでやって初めて「ローカルの限界」と言えるため、調整版を用意して測る。
//
// ── 書き換えの方針 ──
//   1. 短くする（説明文を削り、1項目1〜3行に）
//   2. 出力JSONの形を先に示す（小さいモデルは形が先にあると安定する）
//   3. 例示を「網羅ではない」と明示する ← 例示リストを閉じた集合と解釈する挙動への対処
//   4. 否定文を減らす。抽象語（実質的・看過できない）を具体的な言い方に置き換える
//
// ── 意図的にやっていないこと ──
// 落ちたケースの正解をそのまま書き足すことはしない。たとえば「経管栄養」は
// medical の例示に足していない。足せばそのケースは通るが、
// 「指定しなくても判断できるか」が測れなくなるため。
//
// 使い方:
//   node --env-file=.env scripts/eval-extract.js --model=ollama:qwen2.5:7b --prompt=scripts/prompt-variants/local-7b.js

export function buildPrompt(text, { year = new Date().getFullYear() } = {}) {
  return `介護記録から情報を抜き出して、JSONだけを返してください。説明や前置きは不要です。

# 返すJSONの形

{"date":"","kyotaku":"","staff":"","care":"","medical":false,"result":"watch","trouble":false,"discrepancy":false,"summary":""}

# 各項目の決め方

## date（利用日）
YYYY-MM-DD の形。
年が書いていなければ ${year}年。
「7/14〜7/16」のような期間は開始日。
日付が全く書いていなければ ""。今日の日付で埋めないこと。

## kyotaku（紹介元の事業所名）
書いてあるとおりに写す。法人格も省かない。
紹介元だけ。文中に別の事業所名が出てきても入れない。
無ければ ""。

## staff（紹介元の担当ケアマネ）
姓だけ。敬称や肩書きは外す。
「高橋さん」「高橋CM」「担当: 高橋」「高橋一郎さん」→ すべて "高橋"
自分の施設の職員（看護師など）や利用者の名前は入れない。
担当が交代していたら、新しい方の姓。
書いていなければ ""。

## care（要介護度）
「要支援1」「要支援2」「要介護1」〜「要介護5」のどれかをそのまま。
確定していなければ ""。（例：「確認中」「申請中」「暫定で」と書かれている場合）

## medical（看護師の処置が要ったか）
インスリン、点滴、痰吸引、褥瘡処置 など、看護師でないとできない処置があれば true。
**これは例です。ここに挙げていない看護処置も true にしてください。**
薬を飲ませる・管理するだけなら false。
過去にやっていたが今はやっていない処置も false。
はっきり書かれていなければ false。

## result（今後どうなるか）
また使いそう → "regular"
今回で終わり → "single"
まだ決まっていない → "watch"
迷ったら "watch"。

## trouble（紹介元のせいで困ったか）
紹介元の落ち度で現場が困ったら true。
例：連絡が無かった。伝えるべきことを伝えていなかった。約束が守られなかった。
次の場合は false：
・自分の施設のミス（送迎の手配漏れ、職員どうしの対立など）
・利用者どうしのいさかい
・ご家族からの苦情
・事前情報のズレが原因で困った場合（このときは discrepancy だけ true）

## discrepancy（事前情報とのズレ）
事前に聞いていた話と実際が違い、**現場の負担が重くなった**なら true。
例：「穏やかと聞いていたが、実際は介助量が多かった」→ true
次の場合は false：
・実際の方が楽だった（手がかからなかった）
・「少し表情が硬い」程度の小さな違い
・比較する事前情報が書かれていない

## summary
様子を1〜2文で。

# 守ること

書いていないことは足さない。分からない項目は "" か false のままにする。
書いてあることは見落とさない。

# 記録文

${text}`;
}
