// 記録抽出のプロンプトとモデル設定の「唯一の定義」。
//
// 本番API（api/extract.js）と eval（scripts/eval-extract.js）の両方がここを import する。
//
// ── 分離した理由 ──
// 以前は本番APIとevalが別々のプロンプトを持っていた。その結果、evalで検証して
// 勝った判定基準（staffの正規化・discrepancyの軽微/実質の線引き・盛らない方針）が
// 本番に一つも反映されていない状態になっていた。
// 「測ったもの」と「動くもの」を構造的に一致させるため、定義はここ1箇所に置く。

// 抽出モデル。Vercel の環境変数 MODEL_EXTRACT で切替可能。
export const MODEL = process.env.MODEL_EXTRACT || "claude-haiku-4-5";

// 採点対象のフィールド（summary は自由文なので採点対象外）
export const FIELDS = [
  "date", "kyotaku", "staff", "care", "medical", "result", "trouble", "discrepancy",
];

/**
 * 記録文から抽出プロンプトを組み立てる。
 *
 * @param {string} text  介護記録の本文
 * @param {object} [opts]
 * @param {number} [opts.year]  記録文に年の記載が無い場合に補う年。
 *   本番では実行時の年（記録は当年に書かれるため）。
 *   evalでは正解データに合わせて明示的に固定する（再現性のため）。
 */
export function buildPrompt(text, { year = new Date().getFullYear() } = {}) {
  return `あなたは介護施設の相談員として、居宅・ケアマネから来た利用者の記録を読み取ります。次の記録文から項目を抽出し、JSONオブジェクトだけを返してください（前置き・マークダウン記号は不要）。

抽出項目と判定基準:
- date: 利用日。YYYY-MM-DD。年が無ければ${year}年とする。無ければ ""
- kyotaku: 紹介元の居宅・ケアマネ事業所名。無ければ ""
- staff: 紹介元の担当ケアマネの氏名。**姓のみ・敬称なし**に正規化する（例：「高橋さん」「担当:高橋」「高橋CM」「ケアマネの高橋さん」→ すべて "高橋"）。
  注意：自施設の職員（看護師・介護職員など）や利用者本人の名前は staff ではない。**紹介元の居宅側の担当者だけ**を入れる。書かれていなければ ""。
- care: 要介護度。要支援1／要支援2／要介護1〜要介護5 のいずれかに厳密一致。不明なら ""
- medical: インスリン・点滴・痰吸引・褥瘡処置など"具体的な看護処置の記載がある時だけ" true。曖昧な表現では true にしない。
- result: 継続の見込み="regular"／今回で終了="single"／未確定・様子見="watch"。判断できなければ "watch"。
- trouble: 現場の問題・対立・混乱の記載がある時だけ true。
- discrepancy: 事前に聞いていた情報と実際が食い違い、かつその差が現場的に"看過できない実質的なもの"のとき true（例：想定より介助量が多い／状態が想定より重い など）。原因が介助量・忙しさでも、実質的な負荷差なら true。
  一方、事前との差が"軽微な様子の変化"にとどまり「大きな異常ではない」と読める場合は true にしない（例：表情が少し硬い／食事が少しゆっくり 程度）。
  例：「穏やかと聞いていたが実際は介助量が多かった」→ true。「特に問題なしと聞いていたが少し表情が硬い程度、大きな異常なし」→ false。
  対比が無く単に「忙しい」「大変」だけの場合も true にしない。
- summary: 様子を1〜2文で簡潔に。

重要な方針（盛らない）:
- 根拠のない項目は空文字 "" または false にする。推測で埋めない。
- 記録文に書かれていない医療対応・トラブル・食い違いを、勝手に付け足さない。
- ただし、書かれている異変（食い違い・トラブル・医療処置）は絶対に見落とさない。

【記録文】
${text}`;
}
